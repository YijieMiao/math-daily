"""Refresh the historical batches included in the WeChat preview."""
import base64
import gzip
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
wechat = root / "wechat"


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def build():
    index = json.loads((root / "data/archive.json").read_text())
    config_path = wechat / "app.json"
    config = json.loads(config_path.read_text())
    existing = [entry for entry in config["subPackages"] if not entry["root"].startswith("history-")]
    records = json.loads((root / "data/ai-disclosures.json").read_text())["records"]
    packages = []
    manifest = {}
    size = 0
    for entry in index:
        date = entry["date"]
        batch = json.loads((root / f"data/archive/{date}.json").read_text())
        audits = {p["id"]: records[p["id"]] for p in batch["papers"]
                  if p["id"] in records and records[p["id"]]["announcement_date"] == date}
        payload = base64.b64encode(gzip.compress(compact({"batch": batch, "records": audits}).encode(), mtime=0)).decode()
        if not packages or size + len(payload) > 1_650_000:
            name = f"history-{len(packages) + 1}"
            packages.append({"root": name, "pages": ["loader"]})
            folder = wechat / name
            folder.mkdir(exist_ok=True)
            (folder / "loader.js").write_text("Page({});\n")
            (folder / "loader.wxml").write_text("")
            size = 0
        (folder / f"{date}.js").write_text(f"module.exports = '{payload}';\n")
        manifest[date] = f"./{name}/{date}.js"
        size += len(payload)
    config["subPackages"] = existing + packages
    config_path.write_text(json.dumps(config, indent=2) + "\n")
    loaders = ",\n".join(f"  '{date}': () => require.async('{path}')" for date, path in manifest.items())
    (wechat / "archive-local.js").write_text(
        "// Generated by scripts/build_wechat_archive.py.\n"
        f"const index = {compact(index)};\nconst loaders = {{\n{loaders}\n}};\n"
        "module.exports = { index, loaders };\n"
    )
    print(f"{len(index)} batches across {len(packages)} subpackages")


if __name__ == "__main__":
    build()
